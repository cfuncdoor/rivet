// build.rivet.cpp for the buildscript-demo package.
//
// rivet compiles this file with the detected toolchain (C++17 minimum,
// package `include/` on the path) and runs it with the package dir as the
// working directory BEFORE the main build. Its `rivet:` stdout lines feed
// the main build:
//
//   rivet:include <dir>            extra -I dir for the main build
//   rivet:define <K[=V]>           extra -D for the main build
//   rivet:rerun-if-changed <path>  rebuild trigger (this script itself is
//   rivet:rerun-if-env <VAR>       always a trigger too)
//
// Anything else it prints goes to the build log. Hermetic: only writes
// inside the package dir, no network.
//
// This script generates `generated/build_info.h` (consumed by
// src/main.cpp via the emitted include dir) and defines HAVE_BUILD_INFO.
#include <cstdio>
#include <system_error>
#include <filesystem>
#include <fstream>

namespace fs = std::filesystem;

int main() {
  std::error_code ec;
  fs::create_directories("generated", ec);
  if (ec) {
    std::fprintf(stderr, "build script: cannot create generated/: %s\n", ec.message().c_str());
    return 1;
  }
  std::ofstream hdr("generated/build_info.h");
  if (!hdr) {
    std::fprintf(stderr, "build script: cannot write generated/build_info.h\n");
    return 1;
  }
  hdr << "#pragma once\n";
  hdr << "// Generated by build.rivet.cpp — do not edit.\n";
  hdr << "#define BUILD_INFO_VERSION \"0.1.0-generated\"\n";
  hdr.close();

  std::printf("rivet:include generated\n");
  std::printf("rivet:define HAVE_BUILD_INFO=1\n");
  std::printf("rivet:rerun-if-changed build.rivet.cpp\n");
  std::printf("generated build_info.h\n");
  return 0;
}
